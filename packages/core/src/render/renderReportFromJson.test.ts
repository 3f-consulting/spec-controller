/**
 * Unit tests for renderReportFromJson — the render-from-saved-JSON seam (@SCN-RMD-007).
 *
 * Bidirectional evidence (Evidence Manifesto §9): the describe carries @SCN-RMD-007, matching
 * features/report-model.feature, so a grep of the id returns both halves (this @unit + the
 * Cucumber @integration step-block).
 *
 * Proves the parse→renderReport drift-equality in isolation: the markdown regenerated from a
 * banked spec-reconciliation.json ALONE (renderReportFromJson) equals the markdown rendered
 * directly from the same run (renderMarkdown). The corpus spans the WHOLE document — the
 * three-way test-volume line, the materialised summary totals, the static-guard reconciliation,
 * and a CODED out-of-balance feature — so the by-feature TITLE path has teeth: without the
 * feature titles on the JSON (@SCN-RMD-006) the regenerated by-feature cut would name the bare
 * code and diverge.
 *
 * Parent: (@SCN-RMD-007).
 */

import { describe, it, expect } from "vitest";
import { renderJson } from "./json.js";
import { renderReportFromJson, renderMarkdown } from "./markdown.js";
import type { Ledger, Scenario, EvidenceObservation } from "../model.js";
import type { RunContext } from "../provenance/provenance.js";
import type { RuntimeEvidenceObservationKindCounts } from "../census/evidenceObservations.js";
import { countRuntimeEvidenceObservationKinds } from "../census/evidenceObservations.js";
import { reconcile } from "../reconcile/reconcile.js";
import type { StaticEvidenceObservationKindCounts } from "../census/staticEvidenceObservations.js";
import type { EvidenceObligations } from "../census/evidenceObligations.js";

// RECONCILER-TRUE FIXTURE (evidence-manifesto §11A, 3F-1894). The balance is PRODUCED by
// reconcile() over a corpus, and the runtime census (below) is a FOLD over it — so the census
// cannot claim a phantom/suspense/attribution the ledger does not carry. The round-trip banks the
// ledger to disk, so the phantom the census counts must exist as an actual ROW, not a bare count
// (3F-1861). The CHK feature carries a balanced unit scenario and an out-of-balance integration
// scenario, so the by-feature cut names "checkout (CHK)". The corpus:
//   SCN-CHK-001: @unit, one passing unit credit → balanced, attributed 1
//   SCN-CHK-002: @integration, no credit → integration missing (the coded out-of-balance feature)
//   1 unit credit citing SCN-PHX-001 (undeclared) → a real phantom ROW, phantom 1
//   1 uncited unit credit (src/b.test.ts) + the undemanded lint:bar static guard → the suspense row
const scenarios: Scenario[] = [
  { scnId: "SCN-CHK-001", evidenceObligations: [{ qualityCheck: "unit" }] },
  { scnId: "SCN-CHK-002", evidenceObligations: [{ qualityCheck: "integration" }] },
];
const observations: EvidenceObservation[] = [
  { qualityCheck: "unit", scnId: "SCN-CHK-001", status: "passed" },
  { qualityCheck: "unit", scnId: "SCN-PHX-001", status: "passed" },
  { qualityCheck: "unit", scnId: null, status: "passed", locator: "src/b.test.ts" },
  { qualityCheck: "lint", staticGuard: "lint:bar", exists: true, enforcedOverRealSource: true },
];
const balance: Ledger = reconcile(scenarios, observations);

const ctx: RunContext = {
  target: "roundtrip-fixture",
  inputs: { features: "tests/fixtures/roundtrip/features" },
  runStart: new Date("2026-07-02T09:00:00.000Z"),
  sourceSha: null,
};

// A three-way evidenceObservations: 3 raw = 1 attributed-to-declared + 1 phantom + 1 suspense.
// FOLDED from the balance above (@SCN-RPT-023), so it cannot diverge from the rows it summarises.
const evidenceObservations: RuntimeEvidenceObservationKindCounts =
  countRuntimeEvidenceObservationKinds(balance);

// The static-guard kind-counts: 2 running CI guards = 1 declared (lint:foo) + 1 uncited (lint:bar).
const guards: StaticEvidenceObservationKindCounts = { runningGuardCount: 2, uncitedStaticGuardCount: 1 };

const evidenceObligations: EvidenceObligations = {
  rawScnOccurrences: 4,
  scenarioCount: 2,
  excludedOccurrences: 2,
  untaggedScenarios: [],
  proseOnlyCodes: [],
};

const featureNames = new Map([["CHK", "checkout"]]);

describe("[SCN-RMD-007] the markdown regenerates from a saved spec-reconciliation.json alone", () => {
  it("regenerates markdown byte-identical to the direct render (drift-equality)", () => {
    const savedJson = renderJson(balance, ctx, evidenceObligations, evidenceObservations, guards, featureNames);
    const regenerated = renderReportFromJson(savedJson);
    const direct = renderMarkdown(balance, ctx, evidenceObligations, evidenceObservations, featureNames, guards);
    expect(regenerated).toBe(direct);
  });

  it("names the coded out-of-balance feature in full from the JSON alone (the by-feature title teeth)", () => {
    const savedJson = renderJson(balance, ctx, evidenceObligations, evidenceObservations, guards, featureNames);
    const regenerated = renderReportFromJson(savedJson);
    // The by-feature title comes from report.metadata.featureNames on the saved JSON (@SCN-RMD-006)
    // — a regenerate without the titles would name the bare "CHK".
    expect(regenerated).toContain("| checkout (CHK) | 1 | SCN-CHK-002 |");
  });

  it("carries the whole document — the three-way test-volume line and the materialised summary totals", () => {
    const savedJson = renderJson(balance, ctx, evidenceObligations, evidenceObservations, guards, featureNames);
    const regenerated = renderReportFromJson(savedJson);
    // The three-way test-volume identity survives the round-trip.
    expect(regenerated).toContain("3 evidence observations = 1 attributed + 1 cites-unknown-scenario + 1 cites-no-scenario.");
    // The static-guard counts line (a materialised summary total) survives too.
    expect(regenerated).toContain("2 static guard(s) run, 1 uncited static guard(s).");
    // The SUSPENSE row survives the round-trip — its S bullet, its ledger cell
    // (with the re-homed static guard + the uncited-credit locator), and its cites-no-scenario items.
    expect(regenerated).toContain('1 suspense-scenario(s): credits citing no scenario, aggregated into "(no scenario)".');
    expect(regenerated).toContain("lint ❓ Evidence Observation cites no Scenario (lint:bar)");
    expect(regenerated).toContain("unit ❓ Evidence Observation cites no Scenario (src/b.test.ts)");
  });

  it("needs no RunContext — the JSON string alone reconstructs the report", () => {
    // The seam takes ONLY the JSON string; the run provenance header is rebuilt from the JSON's
    // runProvenance section, not a live RunContext.
    const savedJson = renderJson(balance, ctx, evidenceObligations, evidenceObservations, guards, featureNames);
    const regenerated = renderReportFromJson(savedJson);
    expect(regenerated).toContain("## Run provenance");
    expect(regenerated).toContain("- Target repo: roundtrip-fixture");
  });
});
